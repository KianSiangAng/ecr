"""Extract the SUSS interim course schedule PDF into schedule-data.js for the planner.

Usage:
    pip install pdfplumber
    python scripts/extract_schedule.py [Full_Interim_Course_Schedule.pdf] [schedule-data.js]

Each PDF row is one session (or one written exam) of one class. Rows are grouped
into courses -> classes (CRN / TG) -> sessions, and dates/times are packed as
integers to keep the file small:
    day   = days since 1970-01-01
    start = minutes after midnight
"""

import datetime as dt
import json
import re
import sys
from collections import defaultdict

import pdfplumber

COLUMNS = [
    "sn", "postgraduate", "school", "code", "cls", "semester", "language",
    "mode", "weekday", "date", "start", "end", "campus", "gsp", "remarks",
]
EPOCH = dt.date(1970, 1, 1)
MODES = ["FACE-TO-FACE", "ONLINE", "LABORATORY", "VIRTUAL LABORATORY"]
CAMPUSES = ["CLE", "AMK", "EXT", "ONL"]
EXAM = "WRITTEN EXAM"
RESTRICTED = 1
VIRTUAL_LAB_NOTE = 2


def clean(cell):
    return re.sub(r"\s+", " ", cell or "").strip()


def read_rows(pdf_path):
    rows = []
    with pdfplumber.open(pdf_path) as pdf:
        for page in pdf.pages:
            for table in page.extract_tables():
                for raw in table:
                    if len(raw) != len(COLUMNS) or not clean(raw[0]).isdigit():
                        continue  # notes block and header row
                    rows.append(dict(zip(COLUMNS, map(clean, raw))))
    return rows


def day_number(text):
    date = dt.datetime.strptime(text, "%d/%m/%Y").date()
    return (date - EPOCH).days


def minutes(text):
    t = dt.datetime.strptime(text, "%I:%M:%S %p")
    return t.hour * 60 + t.minute


def class_sort_key(name):
    prefix, num = re.match(r"([A-Z]+)(\d+)", name).groups()
    return (prefix != "CRN", int(num))


def school_name(text):
    words = []
    for word in text.split(" "):
        if word in ("OF", "AND"):
            words.append(word.lower())
        elif word in ("SUSS", "S", "R") or word.startswith("IAL-"):
            words.append(word.split("-")[0] + word[len(word.split("-")[0]):].title())
        else:
            words.append(word.title())
    return " ".join(words)


def build(rows):
    schools = sorted({r["school"] for r in rows})
    courses = defaultdict(lambda: {"classes": defaultdict(list)})
    for r in rows:
        course = courses[r["code"]]
        course["school"] = schools.index(r["school"])
        course["pg"] = 1 if r["postgraduate"] == "Yes" else 0
        course["classes"][r["cls"]].append(r)

    out = []
    for code in sorted(courses):
        course = courses[code]
        classes = []
        for name in sorted(course["classes"], key=class_sort_key):
            sessions, exam, flags = [], 0, 0
            first = course["classes"][name][0]
            gsp = 0
            for r in course["classes"][name]:
                if r["remarks"] == "Restricted":
                    flags |= RESTRICTED
                elif r["remarks"].startswith("There are Virtual Lab"):
                    flags |= VIRTUAL_LAB_NOTE
                slot = [day_number(r["date"]), minutes(r["start"]), minutes(r["end"])]
                if r["mode"] == EXAM:
                    exam = slot + [CAMPUSES.index(r["campus"])]
                    continue
                if r["gsp"] == "Yes":
                    gsp = 1
                sessions.append(slot + [MODES.index(r["mode"]), CAMPUSES.index(r["campus"])])
            sessions.sort()
            classes.append([
                name,
                "S" if first["semester"] == "Special" else "R",
                first["language"].title(),
                gsp,
                flags,
                sessions,
                exam,
            ])
        out.append([code, course["school"], course["pg"], classes])
    return {"schools": [school_name(s) for s in schools], "courses": out}


def main():
    pdf_path = sys.argv[1] if len(sys.argv) > 1 else "Full_Interim_Course_Schedule.pdf"
    out_path = sys.argv[2] if len(sys.argv) > 2 else "schedule-data.js"
    rows = read_rows(pdf_path)
    data = build(rows)
    data = {
        "source": pdf_path.rsplit("/", 1)[-1],
        "rows": len(rows),
        "modes": ["Face-to-face", "Online", "Laboratory", "Virtual lab"],
        "campuses": CAMPUSES,
        **data,
    }
    with open(out_path, "w") as f:
        f.write("// Generated by scripts/extract_schedule.py from " + data["source"] + ". Do not edit by hand.\n")
        f.write("window.ECR_DATA = ")
        json.dump(data, f, separators=(",", ":"))
        f.write(";\n")
    n_classes = sum(len(c[3]) for c in data["courses"])
    print(f"{len(rows)} rows -> {len(data['courses'])} courses, {n_classes} classes -> {out_path}")


if __name__ == "__main__":
    main()
